import fs from 'node:fs';

function replaceOrFail(text, from, to, label) {
  if (!text.includes(from)) throw new Error(`Missing target: ${label}`);
  return text.replace(from, to);
}

// Journal detail: make account/party searchable intent explicit.
{
  const path = 'src/modules/accounting/JournalEntryDetail.tsx';
  let s = fs.readFileSync(path, 'utf8');
  s = replaceOrFail(
    s,
    '<SearchableSelect\n                                className="input bg-white w-full"\n                                value={\n                                  line.accountId\n                                }',
    '<SearchableSelect\n                                className="input bg-white w-full"\n                                searchPlaceholder="Search account by code or name..."\n                                emptyText="No posting account found"\n                                value={\n                                  line.accountId\n                                }',
    'journal account searchable select',
  );
  s = replaceOrFail(
    s,
    '<SearchableSelect\n                                className="input bg-white w-full"\n                                value={\n                                  line.partyType &&',
    '<SearchableSelect\n                                className="input bg-white w-full"\n                                searchPlaceholder="Search customer or supplier..."\n                                emptyText="No matching customer / supplier"\n                                value={\n                                  line.partyType &&',
    'journal party searchable select',
  );
  fs.writeFileSync(path, s);
}

// Journal list: expose Template in the main action bar and make it a real XLSX template.
{
  const path = 'src/modules/accounting/JournalEntryList.tsx';
  let s = fs.readFileSync(path, 'utf8');

  if (!s.includes('import * as XLSX from "xlsx";')) {
    s = replaceOrFail(
      s,
      'import { useNavigate } from "react-router-dom";\n\n',
      'import { useNavigate } from "react-router-dom";\nimport * as XLSX from "xlsx";\n\n',
      'xlsx import',
    );
  }

  const oldFnStart = 'const downloadExcelTemplate = () => {';
  const fnStart = s.indexOf(oldFnStart);
  const componentMarker = '/* =========================================================\n   COMPONENT\n========================================================= */';
  const fnEnd = s.indexOf(componentMarker, fnStart);
  if (fnStart < 0 || fnEnd < 0) throw new Error('Could not locate downloadExcelTemplate function');

  const realFn = `const downloadExcelTemplate = () => {\n  const worksheet = XLSX.utils.aoa_to_sheet([TEMPLATE_HEADERS, ...TEMPLATE_ROWS]);\n  worksheet["!cols"] = [\n    { wch: 18 }, { wch: 14 }, { wch: 34 }, { wch: 18 },\n    { wch: 30 }, { wch: 34 }, { wch: 16 }, { wch: 16 },\n  ];\n  worksheet["!autofilter"] = { ref: \`A1:H\${TEMPLATE_ROWS.length + 1}\` };\n  const workbook = XLSX.utils.book_new();\n  XLSX.utils.book_append_sheet(workbook, worksheet, "Journal Import");\n  XLSX.writeFile(workbook, "journal-import-template.xlsx");\n};\n\n`;
  s = s.slice(0, fnStart) + realFn + s.slice(fnEnd);

  s = s.replace(
    'if (\n        extension !== "csv" &&\n        extension !== "xls"\n      ) {\n        throw new Error(\n          "Please upload CSV or the Excel-compatible XLS template generated by this page."\n        );\n      }\n\n      const text =\n        await file.text();\n\n      let rawRows: string[][];\n\n      if (extension === "xls") {\n        rawRows =\n          parseExcelCompatibleHTML(\n            text\n          );\n      } else {\n        rawRows =\n          parseCSV(text);\n      }',
    'if (\n        extension !== "csv" &&\n        extension !== "xls" &&\n        extension !== "xlsx"\n      ) {\n        throw new Error(\n          "Please upload CSV, XLS or XLSX journal template."\n        );\n      }\n\n      let rawRows: string[][];\n\n      if (extension === "xls" || extension === "xlsx") {\n        const buffer = await file.arrayBuffer();\n        const workbook = XLSX.read(buffer, { type: "array" });\n        const firstSheetName = workbook.SheetNames[0];\n        if (!firstSheetName) throw new Error("The Excel workbook has no worksheet.");\n        rawRows = XLSX.utils.sheet_to_json(workbook.Sheets[firstSheetName], {\n          header: 1, raw: false, defval: "",\n        }) as string[][];\n      } else {\n        rawRows = parseCSV(await file.text());\n      }',
  );

  const actionsStart = '<div className="flex flex-wrap gap-2">\n\n          <button';
  if (!s.includes(actionsStart)) throw new Error('Could not locate journal header actions');
  s = s.replace(
    actionsStart,
    `<div className="flex flex-wrap gap-2">\n\n          <button\n            type="button"\n            onClick={downloadExcelTemplate}\n            className="px-4 py-2.5 text-sm font-semibold flex items-center gap-2 border border-slate-300 bg-white hover:bg-slate-50 text-slate-700 rounded-lg"\n          >\n            ↓ Template (.xlsx)\n          </button>\n\n          <button`,
  );

  // Remove legacy MetalForge wording from journal voucher print output while here.
  s = s.replaceAll('MetalForge OS', 'NAVILO');

  fs.writeFileSync(path, s);
}

console.log('Journal searchable controls and real XLSX template standardized.');
